import { randomUUID } from 'node:crypto';
import { afterAll, beforeAll, expect, it } from 'vitest';
import { isolatedBatchDatabase } from './isolated-batch-database.js';
import { TwitchNativeAuthority } from '../src/application/twitch/twitch-native-authority.js';
import type { AppConfig } from '../src/config/environment.js';
const fixture = isolatedBatchDatabase(), db = fixture.database;
const capability = { enabled: true, globalEnabled: true };
const config = { twitchCommandPilot: capability } as AppConfig;
const authority = new TwitchNativeAuthority(db, config);
beforeAll(async () => fixture.setup({ prismaMigrations: true }), 60_000);
afterAll(async () => fixture.cleanup(), 60_000);
it('keeps exact state/coverage predicates in a single fresh snapshot through authority, identity and link changes', async () => {
  const user = '900000001', key = 'twitch-commands';
  expect(await authority.readAdmission(user)).toEqual({ state: { desiredMode: 'OFF', revision: 0, operatorPlayerId: null }, covered: false });
  const operator = await db.player.create({ data: { id: randomUUID(), displayName: 'Private operator' } });
  await db.twitchNativeAuthority.create({ data: { id: key, desiredMode: 'GLOBAL', revision: 1, operatorPlayerId: operator.id, acknowledgement: 'STREAMERBOT_PATH_DISABLED', acknowledgedAt: new Date() } });
  expect(await authority.readAdmission(user)).toMatchObject({ state: { desiredMode: 'GLOBAL', revision: 1 }, covered: true });
  capability.globalEnabled = false;
  expect((await authority.readAdmission(user)).covered).toBe(false);
  capability.globalEnabled = true;
  await db.twitchNativeAuthority.update({ where: { id: key }, data: { desiredMode: 'CANARY', revision: 2 } });
  expect((await authority.readAdmission(user)).covered).toBe(false);
  await db.twitchNativeTarget.create({ data: { twitchUserId: user, dataAuthority: 'NATIVE', canary: true, acknowledgement: 'STREAMERBOT_PATH_DISABLED', transferredAt: new Date() } });
  expect((await authority.readAdmission(user)).covered).toBe(true);
  const player = await db.player.create({ data: { id: randomUUID(), displayName: 'Private admission fixture', webIdentity: { create: { provider: 'supabase', providerSubject: randomUUID() } } }, include: { webIdentity: true } });
  await db.twitchIdentity.create({ data: { playerId: player.id, twitchUserId: user, login: 'privatefixture' } });
  expect((await authority.readAdmission(user)).covered).toBe(false);
  await db.twitchNativeTarget.update({ where: { twitchUserId: user }, data: { playerId: player.id } });
  expect((await authority.readAdmission(user)).covered).toBe(true);
  const webPlayer = await db.player.create({ data: { id: randomUUID(), displayName: 'Private web account', webIdentity: { create: { provider: 'supabase', providerSubject: randomUUID() } } }, include: { webIdentity: true } });
  const resolution = await db.twitchLinkResolution.create({ data: { webIdentityId: webPlayer.webIdentity!.id, webPlayerId: webPlayer.id, twitchPlayerId: player.id, twitchUserId: user, login: 'privatefixture', comparedState: {}, expiresAt: new Date(Date.now() + 60_000) } });
  expect((await authority.readAdmission(user)).covered).toBe(false);
  await db.twitchLinkResolution.update({ where: { id: resolution.id }, data: { completedAt: new Date(), choice: 'TWITCH' } });
  expect((await authority.readAdmission(user)).covered).toBe(true);
  await db.player.update({ where: { id: player.id }, data: { status: 'SUSPENDED' } });
  expect((await authority.readAdmission(user)).covered).toBe(false);
  await db.twitchNativeAuthority.update({ where: { id: key }, data: { desiredMode: 'OFF', revision: 3 } });
  expect(await authority.readAdmission(user)).toMatchObject({ state: { desiredMode: 'OFF', revision: 3 }, covered: false });
  expect(fixture.migrationStatus).toContain('up to date');
});
